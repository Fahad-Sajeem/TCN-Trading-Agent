def create_sliding_windows(df, feature_cols, label_cols, lookback=200):

    X, y = [], []

    # 🔑 Extract once (IMPORTANT)
    feature_array = df[feature_cols].values
    label_array = df[label_cols].values

    for t in range(lookback - 1, len(df)):

        # skip unlabeled rows
        if np.isnan(label_array[t]).any():
            continue

        x_window = feature_array[
            t - lookback + 1 : t + 1
        ]

        y_target = label_array[t]

        X.append(x_window)
        y.append(y_target)

    X = np.array(X, dtype=np.float32)
    y = np.array(y, dtype=np.float32)

    return X, y

